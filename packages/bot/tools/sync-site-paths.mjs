#!/usr/bin/env node
// Regenerates src/recipes/site-paths.generated.ts from the live sitemap, so the
// bot's "Docs" links always point at a page that exists on the site.
// Usage: node tools/sync-site-paths.mjs [siteUrl]
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const site = (process.argv[2] || "https://prequeluianimate.terravidhal.me").replace(/\/+$/, "");
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "..", "src", "recipes", "site-paths.generated.ts");

const xml = await (await fetch(`${site}/sitemap.xml`)).text();
const paths = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)]
  .map((match) => new URL(match[1]).pathname)
  .filter((pathname) => pathname.startsWith("/components/") && pathname.split("/").length === 4);

const docs = {};
for (const pathname of paths.sort()) {
  const slug = pathname.split("/").at(-1);
  // Base UI pages win when a slug exists twice: they are the primitive's home.
  if (!docs[slug] || pathname.startsWith("/components/base-ui/")) docs[slug] = pathname;
}

const body = `// Generated by tools/sync-site-paths.mjs from ${site}/sitemap.xml. Do not edit.
export const SITE_DOCS: Record<string, string> = ${JSON.stringify(docs, null, 2)};
`;
await writeFile(out, body);
console.log(`site-paths.generated.ts: ${Object.keys(docs).length} component pages`);
