export const meta = {
  "slug": "tabler-folder-open",
  "family": "tabler",
  "name": "folder-open",
  "category": "Files",
  "motion": "file",
  "component": "createTablerFolderOpenIcon"
};

export function createTablerFolderOpenIcon(root, options = {}) {
  let current = { ...options };
  const render = () => {
    root.innerHTML = renderSetIcon(definition, current);
  };
  render();
  const controller = bindSetIcon(root, definition, () => current);
  return {
    play: controller.play,
    reset: controller.reset,
    destroy: controller.destroy,
    update(next = {}) {
      current = { ...current, ...next };
      render();
    },
    get observed() {
      return controller.observed;
    },
  };
}
