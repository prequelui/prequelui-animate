  animation: { type: String, default: "hover" },
});

const definition = {
  "name": "coins",
  "category": "Commerce",
  "viewBox": "0 0 24 24",
  "mode": "stroke",
  "strokeWidth": 2,
  "motion": "coin",
  "parts": [
